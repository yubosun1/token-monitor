  function translate(_locale, key, params = {}) {
    const template = MESSAGES['zh-CN']?.[key] ?? key;
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => {
      return params[name] === undefined || params[name] === null ? '' : String(params[name]);
    });
  }

  function translated(_locale, key) {
    return translate('zh-CN', key);
  }

  function applyTranslations(root, _locale) {
    const scope = root || (typeof document !== 'undefined' ? document : null);
    if (!scope || typeof scope.querySelectorAll !== 'function') return 'zh-CN';
    const docEl = scope.documentElement || scope.ownerDocument?.documentElement;
    if (docEl?.setAttribute) docEl.setAttribute('lang', 'zh-CN');

    for (const el of scope.querySelectorAll('[data-i18n]')) {
      el.textContent = translate('zh-CN', el.dataset.i18n);
    }
    for (const el of scope.querySelectorAll('[data-i18n-title]')) {
      const text = translate('zh-CN', el.dataset.i18nTitle);
      el.title = text;
      if (el.setAttribute) el.setAttribute('title', text);
    }
    for (const el of scope.querySelectorAll('[data-i18n-aria-label]')) {
      const text = translate('zh-CN', el.dataset.i18nAriaLabel);
      if (el.setAttribute) el.setAttribute('aria-label', text);
    }
    for (const el of scope.querySelectorAll('[data-i18n-placeholder]')) {
      const text = translate('zh-CN', el.dataset.i18nPlaceholder);
      el.placeholder = text;
      if (el.setAttribute) el.setAttribute('placeholder', text);
    }
    return 'zh-CN';
  }

